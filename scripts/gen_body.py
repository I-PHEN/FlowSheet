    canvas.line(MARGIN, 0.62 * inch, PAGE_W - MARGIN, 0.62 * inch)
    canvas.setFont('FreeSerif', 7.5)
    canvas.setFillColor(TEXT_MUTED)
    canvas.drawString(MARGIN, 0.45 * inch, DOC_FOOTER_LEFT)
    body_start = getattr(doc, '_body_start_page', None)
    if body_start is None or canvas.getPageNumber() < body_start:
        num = ROMAN.get(canvas.getPageNumber(), str(canvas.getPageNumber()))
    else:
        num = str(canvas.getPageNumber() - body_start + 1)
    canvas.drawRightString(PAGE_W - MARGIN, 0.45 * inch, num)
    canvas.restoreState()


