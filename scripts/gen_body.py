def TBL(headers, rows, ratios, caption=None, font_size=9, align_map=None):
    """Table with Paragraph-wrapped cells, palette colors, centered."""
    assert abs(sum(ratios) - 1.0) < 1e-6, 'ratios must sum to 1'
    col_w = [r * AVAIL_W for r in ratios]
    hstyle = ParagraphStyle('h_tmp', parent=S['cellh'], fontSize=font_size + 0.2)
    cstyle = ParagraphStyle('c_tmp', parent=S['cell'], fontSize=font_size)
    ccstyle = ParagraphStyle('cc_tmp', parent=S['cellc'], fontSize=font_size)
    align_map = align_map or {}
    data = [[Paragraph('<b>%s</b>' % h, hstyle) for h in headers]]
    for row in rows:
        cells = []
        for j, cell in enumerate(row):
            st = ccstyle if align_map.get(j) == 'c' else cstyle
            cells.append(Paragraph(_glue(cell), st))
        data.append(cells)
    t = Table(data, colWidths=col_w, hAlign='CENTER', repeatRows=1)
    style_cmds = [
        ('BACKGROUND', (0, 0), (-1, 0), TABLE_HEADER_COLOR),
        ('TEXTCOLOR', (0, 0), (-1, 0), colors.white),
        ('GRID', (0, 0), (-1, -1), 0.4, BORDER),
        ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
        ('LEFTPADDING', (0, 0), (-1, -1), 6),
        ('RIGHTPADDING', (0, 0), (-1, -1), 6),
        ('TOPPADDING', (0, 0), (-1, -1), 5),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 5),
    ]
    for i in range(1, len(data)):
        bg = TABLE_ROW_ODD if i % 2 == 0 else TABLE_ROW_EVEN
        style_cmds.append(('BACKGROUND', (0, i), (-1, i), bg))
    t.setStyle(TableStyle(style_cmds))
    story.append(Spacer(1, 8))
    if caption:
        cap = Paragraph(caption, S['caption'])
        if len(rows) <= 12:
            story.append(KeepTogether([t, cap]))
        else:
            story.append(t)
            story.append(cap)
    else:
        story.append(t)
    story.append(Spacer(1, 10))


def CHART(filename, caption, max_h=270):
    path = os.path.join(ASSETS, filename)
    pil = PILImage.open(path)
    ow, oh = pil.size
    ratio = min(AVAIL_W / ow, max_h / oh, 1.0)
    img = Image(path, width=ow * ratio, height=oh * ratio)
    cap = Paragraph(caption, S['caption'])
    story.append(Spacer(1, 14))
    story.append(KeepTogether([img, cap]))
    story.append(Spacer(1, 14))


